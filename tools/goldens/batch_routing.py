SRC = {
    "S1": "s1_early_steps_bundle.md", "S2": "s2_frameworks_bundle.md",
    "S3": "s3_lifecycle_bundle.md", "S4": "s4_qa_deep_dives.md", "S5": "s5_docs_bundle.md",
}
bund = {k: open(DATA + v, encoding="utf-8").read() for k, v in SRC.items()}
lines = {k: v.splitlines(keepends=True) for k, v in bund.items()}

def A(src, nums, marker):
    txt = "".join(lines[src][i - 1] for i in nums).rstrip("\n")
    assert marker in txt, f"MARKER FAIL {src} {nums}: {marker!r} -> {txt[:80]!r}"
    assert txt in bund[src], f"NOT CONTIGUOUS {src} {nums}"
    return txt

def expect_path(srcs):
    return " + ".join("data/docs/" + SRC[s] for s in srcs)

def R(i, cat, q, ans, src, nums, marker, must, ctxsrc=None):
    cs = ctxsrc or src
    return {
        "id": i, "category": cat, "query": q, "ideal_answer": ans,
        "ideal_context": A(cs, nums, marker),
        "must_contain": must, "source": src, "path": expect_path(src.split("+")),
    }

